/*
 * ============================================================
 *  程序改错题 01 —— 交换两个整数（值传递错误，二级超高频）
 *
 *  【原题错误代码】
 *      void swap(int x, int y){ int t=x; x=y; y=t; }
 *      int main(void){ int a=3,b=7; swap(a,b); printf("%d %d",a,b); ... }
 *
 *  错误分析：
 *   形参 x、y 只是实参 a、b 的“复印件”（值传递），函数里交换复印件，
 *   主函数中的 a、b 不会改变。
 *  修正方法：
 *   改用“传址调用”——形参写成指针 int *x,int *y，调用时传 &a,&b，
 *   函数内部通过 *x、*y 才能真正改到外面的变量。
 * ============================================================
 */
#include <stdio.h>

void swap(int *x, int *y)     /* 修正：形参为指针，接收变量地址 */
{
    int t = *x;               /* *x 代表主调函数中的 a */
    *x = *y;
    *y = t;
}

int main(void)
{
    int a = 3, b = 7;
    printf("交换前 a=%d b=%d\n", a, b);
    swap(&a, &b);             /* 修正：实参加 &，把地址传进去 */
    printf("交换后 a=%d b=%d\n", a, b);   /* 7 3，交换成功 */
    return 0;
}
