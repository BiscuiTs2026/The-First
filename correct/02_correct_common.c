/*
 * ============================================================
 *  程序改错题 02 —— 判断相等 与 求平均（三处高频低级错误）
 *
 *  错误1：if (a = b)  —— 单个 = 是“赋值”，会把 b 赋给 a 且条件恒真；
 *                       判断是否相等必须用 ==。
 *  错误2：avg = (a + b) / 2; —— 两个 int 相除是“整数除法”，小数部分被截断；
 *                       要先转成 double：(double)(a+b)/2。
 *  错误3（输入题最常见）：scanf("%d", a); 漏写取地址符，
 *                       正确为 scanf("%d", &a);
 * ============================================================
 */
#include <stdio.h>

int main(void)
{
    int a = 5, b = 8;
    double avg;

    if (a == b)                       /* 修正1：== 才是“相等比较” */
        printf("两数相等\n");
    else
        printf("两数不相等\n");

    avg = (double)(a + b) / 2;        /* 修正2：先转 double，保留小数 */
    printf("平均值 = %.2f\n", avg);   /* 6.50 */
    return 0;
}
