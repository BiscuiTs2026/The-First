/*
 * ============================================================
 *  程序设计题 01 —— 求数组最大值及其下标
 *  题目：编写函数，在长度 n 的数组中找最大值并返回，
 *        同时通过指针参数把最大值“第一次出现的下标”带回。
 *  满分思路：
 *   1) 先假定第 0 个最大：max=a[0]、下标=0；
 *   2) 从第 1 个起逐个比较，发现更大就更新 max 和下标；
 *   3) 用 > 而不是 >=，保证相等时保留“第一次出现”的位置。
 * ============================================================
 */
#include <stdio.h>

int findMax(int a[], int n, int *pos)
{
    int max = a[0], i;
    *pos = 0;
    for (i = 1; i < n; i++) {
        if (a[i] > max) {      /* 严格大于，保留第一次出现的下标 */
            max = a[i];
            *pos = i;
        }
    }
    return max;
}

int main(void)
{
    int a[8] = {4, 9, 2, 15, 7, 15, 1, 8};
    int idx;
    int m = findMax(a, 8, &idx);
    printf("最大值 = %d，第一次出现的下标 = %d\n", m, idx);  /* 15 和 3 */
    return 0;
}
