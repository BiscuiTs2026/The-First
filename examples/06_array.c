/*
 * ============================================================
 *  06_array.c —— 一维数组
 *  对应考点：下标从 0 开始、遍历、求和/平均/最值、逆序、部分初始化
 *  编译运行：gcc -Wall -Wextra -std=c99 06_array.c -o 06_array
 * ============================================================
 */
#include <stdio.h>

int main(void)
{
    /* 相同类型的一批数据，按下标有序存放；长度 5，合法下标 0~4 */
    int a[5] = {88, 72, 95, 60, 80};
    int len = 5;

    /* ---------- 1. 遍历数组 ---------- */
    printf("数组元素：");
    for (int i = 0; i < len; i++)
        printf("%d ", a[i]);
    printf("\n");

    /* ---------- 2. 求和、平均、最大值、最小值（二级高频套路） ---------- */
    int sum = 0;
    int max = a[0];          /* 最值先用第一个元素初始化 */
    int min = a[0];
    for (int i = 0; i < len; i++) {
        sum += a[i];
        if (a[i] > max) max = a[i];
        if (a[i] < min) min = a[i];
    }
    printf("总和=%d  平均=%.1f  最大=%d  最小=%d\n",
           sum, (double)sum / len, max, min);

    /* ---------- 3. 逆序遍历 ---------- */
    printf("逆序输出：");
    for (int i = len - 1; i >= 0; i--)
        printf("%d ", a[i]);
    printf("\n");

    /* ---------- 4. 部分初始化：没给初值的元素自动补 0 ---------- */
    int b[5] = {1, 2};
    printf("b = %d %d %d %d %d\n", b[0], b[1], b[2], b[3], b[4]); /* 1 2 0 0 0 */

    return 0;
}
