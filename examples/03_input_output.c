/*
 * ============================================================
 *  03_input_output.c —— 格式化输出 printf 与键盘输入 scanf
 *  对应考点：格式符 %d/%f/%c/%s/%x/%o、宽度与对齐、scanf 的取地址符 &
 *  编译运行：gcc -Wall -Wextra -std=c99 03_input_output.c -o 03_input_output
 * ============================================================
 */
#include <stdio.h>

int main(void)
{
    int    n = 42;
    double x = 3.14159;
    char   c = 'Z';
    char   s[] = "China";     /* 字符串本质是字符数组，用 %s 输出 */

    /* ---------- 1. printf 常用格式符 ---------- */
    printf("整数 %d；浮点 %f；保留两位 %.2f\n", n, x, x);
    printf("字符 %c；字符串 %s\n", c, s);
    printf("十进制 %d = 八进制 %o = 十六进制 %x\n", n, n, n);

    /* ---------- 2. 宽度与对齐（二级常考“输出格式”题） ---------- */
    printf("[%5d]  宽度5、右对齐，左边补空格\n", n);
    printf("[%-5d] 宽度5、左对齐\n", n);
    printf("[%05d] 宽度5、不足位补 0\n", n);
    printf("[%.3f] 保留 3 位小数\n", x);

    /* ============================================================
     *  3. scanf 键盘输入（需要交互，这里用注释演示，避免自动运行时卡住）
     *
     *  int a;
     *  double b;
     *  scanf("%d %lf", &a, &b);      // 普通变量前【必须】加 &（取地址符）
     *  printf("a=%d, b=%.2f\n", a, b);
     *
     *  易错点：
     *   - scanf 里 double 用 %lf，而 printf 里 double 用 %f 即可；
     *   - scanf 的格式串里不要乱写 \n、提示文字；
     *   - 多个输入用空格/回车/Tab 分隔都可以。
     * ============================================================ */

    return 0;
}
