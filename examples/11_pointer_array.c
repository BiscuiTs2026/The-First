/*
 * ============================================================
 *  11_pointer_array.c —— 指针与数组、字符串
 *  对应考点：数组名是首元素地址、a[i] 等价 *(a+i)、指针移动遍历、字符指针
 *  编译运行：gcc -Wall -Wextra -std=c99 11_pointer_array.c -o 11_pointer_array
 * ============================================================
 */
#include <stdio.h>

int main(void)
{
    int a[5] = {10, 20, 30, 40, 50};

    /* ---------- 1. 数组名就是“首元素地址”，且是常量，不能被赋值 ---------- */
    printf("a = %p，&a[0] = %p（两者相同）\n", (void *)a, (void *)&a[0]);

    /* ---------- 2. 下标法 a[i] 与指针法 *(a+i) 完全等价 ---------- */
    int *p = a;                 /* 等价于 p = &a[0]; 数组名前不加 & */
    for (int i = 0; i < 5; i++)
        printf("a[%d]=%d  等价  *(p+%d)=%d\n", i, a[i], i, *(p + i));

    /* ---------- 3. 指针不断后移来遍历（p++ 让它指向下一个元素） ---------- */
    int *q = a;
    int sum = 0;
    for (int i = 0; i < 5; i++) {
        sum += *q;              /* 取当前指向的值 */
        q++;                    /* 指针后移一个 int（地址实际 +4 字节） */
    }
    printf("指针移动遍历求和 = %d\n", sum);     /* 150 */

    /* ---------- 4. 字符指针指向字符串，逐字符走到 '\0' ---------- */
    const char *s = "hello";    /* 字符串常量不可修改，用 const 更安全 */
    printf("字符指针遍历：");
    while (*s != '\0') {        /* *s 是当前字符，遇到结束符停止 */
        printf("%c ", *s);
        s++;
    }
    printf("\n");

    /*
     * 关键结论：
     *  - p+i 不是简单加 i 个字节，而是向后跳 i 个“元素”（int 就跳 4 字节）；
     *  - 数组名 a 是地址常量，a++、a=p 都是非法的；但指针变量 p 可以 p++。
     */
    return 0;
}
