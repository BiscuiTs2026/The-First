/*
 * ============================================================
 *  01_hello.c —— 第一个 C 程序：Hello, World!
 *  对应考点：程序结构、main 函数、printf 输出、return 返回值
 *  编译：gcc 01_hello.c -o 01_hello
 *  运行：01_hello.exe        （Windows）
 *        ./01_hello          （Linux / macOS）
 * ============================================================
 */

#include <stdio.h>      /* 预处理指令：引入标准输入输出库，printf 就在其中 */

int main(void)          /* main 是程序的“入口”，操作系统从这里开始执行；
                           int 表示函数结束时返回一个整数，
                           void 表示该函数不接收参数 */
{
    printf("Hello, World!\n");     /* printf：把引号里的内容输出到屏幕；
                                      \n 是“换行符”，输出后光标换到下一行；
                                      每条语句末尾都要有分号 ; */

    return 0;           /* 向操作系统返回 0，表示程序“正常结束” */
}
