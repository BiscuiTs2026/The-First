/*
 * ============================================================
 *  10_pointer_basic.c —— 指针基础（二级 C 的重中之重）
 *  对应考点：内存地址、& 取地址、* 解引用、指针变量、指针类型与大小
 *  编译运行：gcc -Wall -Wextra -std=c99 10_pointer_basic.c -o 10_pointer_basic
 *
 *  一句话理解：指针变量里装的不是普通数值，而是“另一个变量的地址”，
 *  通过这个地址就能找到并操作那个变量，像“遥控器”遥控电视机。
 * ============================================================
 */
#include <stdio.h>

int main(void)
{
    int a = 10;

    /* &a：取出变量 a 的地址；int* 表示“指向 int 的指针”类型 */
    int *p = &a;

    printf("a 的值        = %d\n", a);
    printf("&a（a 的地址）= %p\n", (void *)&a);   /* %p 打印地址，习惯转 void* */
    printf("p（存的地址） = %p\n", (void *)p);     /* p 里存的正是 a 的地址 */
    printf("*p（顺着地址找到的值）= %d\n", *p);    /* * 是“解引用”：按地址取值 */

    /* ---------- 通过指针间接修改 a ---------- */
    *p = 20;
    printf("执行 *p = 20 后，a = %d（没直接动 a，a 却被改了）\n", a);

    /* ---------- & 与 * 互为逆运算 ---------- */
    printf("*&a = %d（先取地址再解引用，绕一圈还是 a）\n", *&a);

    /* ---------- 指针本身也要占内存（64 位系统通常是 8 字节） ---------- */
    printf("sizeof(int) = %d，sizeof(int*) = %d\n",
           (int)sizeof(int), (int)sizeof(int *));

    /*
     * 易错提醒：
     *  1) int *p = &a; 这里的 * 是“类型的一部分”，声明 p 是指针；
     *     而 *p = 20;  这里的 * 是“解引用运算符”，两者含义不同。
     *  2) 指针类型必须匹配：int* 指向 int，char* 指向 char，不能乱指。
     *  3) 野指针（没指向有效变量就解引用）非常危险，定义时可先 int *p=NULL;
     */
    return 0;
}
