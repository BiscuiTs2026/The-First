/*
 * ============================================================
 *  程序填空题 02 —— 统计字符串中数字字符 '0'~'9' 的个数
 *  题型：字符数组遍历 + 结束符 + 范围判断 + 计数
 *  原题挖空（括号内为参考答案）：
 *      for (i = 0; s[i] != ___【空1】___; i++)
 *          if (s[i] >= '0' ___【空2】___ s[i] <= '9')
 *              count ___【空3】___;
 * ============================================================
 */
#include <stdio.h>

int countDigit(const char s[])
{
    int count = 0, i;
    for (i = 0; s[i] != '\0'; i++)       /* 【空1】'\0'：字符串结束标志 */
        if (s[i] >= '0' && s[i] <= '9')  /* 【空2】&&：上下界要同时成立 */
            count++;                     /* 【空3】++：计数加 1（=count+1）*/
    return count;
}

int main(void)
{
    char s[] = "ab12cd34e5";
    printf("数字字符个数 = %d\n", countDigit(s));   /* 1、2、3、4、5 共 5 个 */
    return 0;
}
