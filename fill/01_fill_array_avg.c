/*
 * ============================================================
 *  程序填空题 01 —— 求 n 个成绩的平均值
 *  题型：函数 + 数组遍历 + 累加 + 浮点平均
 *  原题挖空（括号内为参考答案）：
 *      for (i = 0; i < ___【空1】___; i++)
 *          sum = sum + ___【空2】___;
 *      return (double)sum / ___【空3】___;
 * ============================================================
 */
#include <stdio.h>

double average(int a[], int n)
{
    int sum = 0, i;
    for (i = 0; i < n; i++)    /* 【空1】n：遍历 n 个元素，合法下标 0~n-1 */
        sum = sum + a[i];      /* 【空2】a[i]：把当前元素累加进 sum */
    return (double)sum / n;    /* 【空3】n：总和÷个数；(double) 防止整数除法丢小数 */
}

int main(void)
{
    int score[6] = {80, 90, 70, 60, 100, 84};
    printf("平均成绩 = %.2f\n", average(score, 6));   /* 484/6 = 80.67 */
    return 0;
}
